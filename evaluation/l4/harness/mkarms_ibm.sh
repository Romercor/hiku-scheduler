#!/usr/bin/bash
# Writes arms/<name>_ibm.txt from arms/<name>.txt with the IBM replay appended to every arm's k6 env:
# the window of the repetition, scaled to a mean of <mean> calls/s (files replay_ibm<mean>_<r>.json).
# usage: mkarms_ibm.sh <mean> <name>...
cd "$(dirname "$0")/arms" || exit 1
m=$1; shift
for n in "$@"; do
  { echo "# $n with the IBM Code Engine replay (5 min windows, one per repetition, mean $m calls/s); generated by mkarms_ibm.sh"
    grep -vE '^\s*(#|$)' "$n.txt" | awk -v r="REPLAY=replay_ibm${m}_{r}.json" '{ $5 = ($5 == "-" || $5 == "") ? r : $5 "," r; print }'
  } > "${n}_ibm.txt"
done
